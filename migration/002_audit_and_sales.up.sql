BEGIN;

CREATE TABLE IF NOT EXISTS audit_log (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name TEXT NOT NULL,
    operation TEXT NOT NULL,
    row_pk TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    changed_by TEXT NOT NULL DEFAULT current_user,
    old_row JSONB,
    new_row JSONB
);

CREATE OR REPLACE FUNCTION write_row_audit()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    pk_value TEXT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        pk_value := to_jsonb(OLD)->>TG_ARGV[0];
        INSERT INTO audit_log(table_name, operation, row_pk, old_row)
        VALUES (TG_TABLE_NAME, TG_OP, pk_value, to_jsonb(OLD));
        RETURN OLD;
    ELSIF TG_OP = 'UPDATE' THEN
        pk_value := to_jsonb(NEW)->>TG_ARGV[0];
        INSERT INTO audit_log(table_name, operation, row_pk, old_row, new_row)
        VALUES (TG_TABLE_NAME, TG_OP, pk_value, to_jsonb(OLD), to_jsonb(NEW));
        RETURN NEW;
    ELSE
        pk_value := to_jsonb(NEW)->>TG_ARGV[0];
        INSERT INTO audit_log(table_name, operation, row_pk, new_row)
        VALUES (TG_TABLE_NAME, TG_OP, pk_value, to_jsonb(NEW));
        RETURN NEW;
    END IF;
END;
$$;

DROP TRIGGER IF EXISTS products_audit_trigger ON products;
CREATE TRIGGER products_audit_trigger
AFTER INSERT OR UPDATE OR DELETE ON products
FOR EACH ROW EXECUTE FUNCTION write_row_audit('product_id');

CREATE OR REPLACE PROCEDURE record_sale(
    p_customer_id BIGINT,
    p_product_id BIGINT,
    p_quantity INTEGER,
    p_unit_price NUMERIC
)
LANGUAGE plpgsql AS $$
DECLARE
    v_stock INTEGER;
    v_sale_id BIGINT;
    v_total NUMERIC(14,2);
BEGIN
    IF p_quantity <= 0 OR p_unit_price < 0 THEN
        RAISE EXCEPTION 'Quantity must be positive and unit price non-negative';
    END IF;

    SELECT stock_quantity INTO v_stock
    FROM products
    WHERE product_id = p_product_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product % not found', p_product_id;
    END IF;
    IF v_stock < p_quantity THEN
        RAISE EXCEPTION 'Insufficient stock: available %, requested %', v_stock, p_quantity;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM customers WHERE customer_id = p_customer_id) THEN
        RAISE EXCEPTION 'Customer % not found', p_customer_id;
    END IF;

    v_total := p_quantity * p_unit_price;
    INSERT INTO sales(customer_id, total_amount)
    VALUES (p_customer_id, v_total)
    RETURNING sale_id INTO v_sale_id;

    INSERT INTO sale_items(sale_id, product_id, quantity, unit_price)
    VALUES (v_sale_id, p_product_id, p_quantity, p_unit_price);

    UPDATE products
    SET stock_quantity = stock_quantity - p_quantity,
        updated_at = now()
    WHERE product_id = p_product_id;
END;
$$;

COMMIT;
